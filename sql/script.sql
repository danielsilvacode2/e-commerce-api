CREATE database ecommerce;

USE ecommerce;

SET
    FOREIGN_KEY_CHECKS = 0;

SET
    FOREIGN_KEY_CHECKS = 1;

--A ENTIDADE DO USUARIO
CREATE TABLE users (
    id VARCHAR(50) PRIMARY KEY,
    user_name VARCHAR(100) NOT NULL,
    user_email VARCHAR(100) NOT NULL UNIQUE,
    user_password VARCHAR(255) NOT NULL,
    user_role ENUM('admin', 'user') NOT NULL DEFAULT 'user',
    verification_code VARCHAR(6),
    is_verified BOOLEAN DEFAULT FALSE,
    code_expires_at DATETIME,
    password_reset_code VARCHAR(255) NULL,
    password_reset_expires_at DATETIME NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

TRUNCATE TABLE users;

DESC users;

SELECT
    *
FROM
    users;

-- A ENTIDADE DO PRODUTO
CREATE TABLE products (
    id VARCHAR(50) PRIMARY KEY,
    product_name VARCHAR(100) NOT NULL,
    product_description VARCHAR(100) NOT NULL,
    product_sku VARCHAR(255) NOT NULL UNIQUE,
    product_price DECIMAL(10, 2) NOT NULL,
    product_image VARCHAR(200) NOT NULL,
    product_quantity INT NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
);

TRUNCATE TABLE products;

SELECT
    *
FROM
    products;

DESC products;

--A ENTIDADE DO CARRINHO DE COMPRAS
CREATE TABLE carts (
    id VARCHAR(50) PRIMARY KEY,
    user_id VARCHAR(50) NOT NULL UNIQUE,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

TRUNCATE TABLE carts;

SELECT
    *
FROM
    carts;

DESC carts;

--  A ENTIDADE DE CARRINHO E PRODUTOS
CREATE TABLE cart_products(
    id VARCHAR(50) PRIMARY KEY,
    cart_id VARCHAR(50) NOT NULL,
    product_id VARCHAR(50) NOT NULL,
    quantity INT NOT NULL,
    isSelect BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (cart_id) REFERENCES carts(id) ON DELETE CASCADE,
    FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

TRUNCATE TABLE cart_products;

SELECT
    *
FROM
    cart_products;

DESC cart_products;